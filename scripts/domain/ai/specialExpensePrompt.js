function buildSpecialExpenseReviewPrompt(entries) {
    var entryLines = entries.map(function (entry, index) {
        return [
            index,
            formatDate(entry.date),
            entry.name || "",
            entry.amount
        ].join("|");
    });

    return `あなたは家計簿の「特別費」カテゴリを厳格に監査するアシスタントです。
判定するのは支出そのものの善悪や必要性ではなく、「通常の生活費予算とは別枠にしてよい支出か」だけです。
項目名には商品名だけでなく購入の背景・理由も含まれる。全文を読み、品目・店名だけで判断しない。
以下は代表例であり、承認対象を旅行や年額課金などの品目だけに限定しない。

承認してよいもの:
- 旅行の交通・宿泊・旅行に直接付随する費用
- 年額課金など、年に一度または低頻度で、あらかじめ予定化しやすい支出
- 医療、故障による修理・買い替えなど、緊急性または不可避性が高い低頻度支出
- 解約・契約変更・転居などの一時的な事情に伴い、生活に必要な設備を返却・交換・再調達する支出。背景と購入の因果関係が項目名に明記され、日常の繰り返し購入や任意の性能向上ではないもの
- その他、項目名に具体的な背景があり、通常の生活費と区別できる一時的・低頻度の支出。事情と支出の関係、一時性、通常費との違いを総合して判断する
- 過去の細かな記録漏れ・集計漏れによって生じた差分を合わせるための調整記録。ただし、名称から差分調整の目的が明確に読み取れるものに限る

承認しないもの:
- 高額というだけの服、趣味、外食、ガジェット、Amazon購入
- 予定外だった、忘れていた、使いすぎたという事情だけの支出
- 実際の生活費を後から特別費に付け替えたもの、または差分調整の目的が名称から判断できないもの
- 名称から内容が判断できない支出

判断の例:
- 「Amazon WiFiルーター・LANケーブル：JCOM解約に伴いレンタル機器を返却するので代替を購入」は、機器返却に伴う一時的な再調達として approved。理由例「返却に伴う通信機器の再調達」
- 「高速なWiFiルーターが欲しいので買い替え」は、任意の性能向上として rejected。理由例「任意の通信機器の買い替え」
- 「毎月の通信料」「必要な日用品」「定期購入を記録し忘れた」は、必要性や記録漏れがあっても通常の継続支出として rejected。
理由を書いてあるだけで自動承認せず、書かれた具体的な事情が通常予算と別枠にする根拠になるかを判断する。記載されていない故障・不可避性などを想像して補わない。

不明な場合は必ず rejected にする。支出を特別費にすることで通常予算を軽く見せないよう、厳しめに判定する。
各行は必ず次の形式で返す:
index|approved または rejected|理由（20文字以内）
理由は必須。項目名の説明も判断材料にし、通常予算と別枠にできる根拠、または別枠にできない根拠を具体的に短く書く。
「承認」「特別費のため」「理由なし」など、判定の繰り返しや根拠のない文言は使わない。
理由の例: 「旅行に伴う宿泊費」「故障による必須機器の交換」「日常的な趣味の購入」
入力の事情だけで自動承認せず、上記の基準に照らして判定する。
説明文、Markdown、コードブロック、JSONは出力しない。

対象の特別費候補:
${entryLines.join("\n")}`;
}
